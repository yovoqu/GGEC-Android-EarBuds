package com.yovo.lib_ggec_audio;

/**
 * 空口帧头序号的字节序。
 *
 * <p><b>为什么必须做成产品可配</b>：本模块是多个产品共用的装配层，但不同产品的固件
 * 在帧头字节序上可能不同：</p>
 * <ul>
 *   <li>部分产品使用<b>小端</b>，沿用多年、已定稿，不得改动其行为；</li>
 *   <li>另一些产品的现场固件使用<b>大端</b>（字节级证据：包首依次为
 *       {@code 00 00 00 00} / {@code 00 00 00 0A} / {@code 00 00 00 14}，
 *       即大端 0 / 10 / 20，每包推进 10 帧；包内帧头 {@code 00 00 00 01}、
 *       {@code 00 00 00 02} 递增）。</li>
 * </ul>
 *
 * <p>把字节序写死在共享层，会让各产品互相牵制：改成大端会破坏既有小端产品，保持小端则
 * 大端产品每包只有首帧（序号 0 在两序下都为 0）能解析、其余全成上亿伪值。因此字节序是
 * <b>产品适配参数</b>，由产品在构造装配层时声明。</p>
 */
public enum AudioWireByteOrder {

    /** 小端：低字节在前。既有产品行为，默认值。 */
    LITTLE_ENDIAN,

    /** 大端：高字节在前。大端固件的现场产品使用。 */
    BIG_ENDIAN
}
